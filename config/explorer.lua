-- palette.lua hands the raw palette to init.lua, for what theme.toml has no key for (the
-- header band).
function M.palette_lua(P)
  local keys = {}
  for k in pairs(P) do keys[#keys + 1] = k end
  table.sort(keys)
  local out = { '-- Generated by config/explorer.lua; edits are overwritten.', 'return {' }
  for _, k in ipairs(keys) do out[#out + 1] = string.format('  %s = %q,', k, P[k]) end
  out[#out + 1] = '}'
  return table.concat(out, '\n') .. '\n'
end

local GENERATED = { 'theme.toml', 'palette.lua' }

-- Writes a file only when its content changed.
local function put(path, text)
  local f = io.open(path, 'r')
  local old = f and f:read('a')
  if f then f:close() end
  if old == text then return true end
  f = io.open(path, 'w')
  if not f then return false end
  f:write(text)
  f:close()
  return true
end

-- Writes the generated files, links every entry of the static config, drops links whose
-- source is gone, and returns the directory for YAZI_CONFIG_HOME. Falls back to the static
-- config, uncoloured, if the cache cannot be written.
function M.config_home()
  local theme = require 'theme'
  if not wezterm.run_child_process { 'mkdir', '-p', CACHE }
      or not put(CACHE .. '/theme.toml', M.theme_toml(theme.P, theme.T))
      or not put(CACHE .. '/palette.lua', M.palette_lua(theme.P)) then
    return SOURCE
  end

  local own = {}
  for _, name in ipairs(GENERATED) do own[name] = true end
  local want, args = {}, { 'ln', '-sfn' }
  for _, src in ipairs(wezterm.read_dir(SOURCE)) do
    local name = src:match('[^/]+$')
    if not own[name] then
      want[name] = true
      args[#args + 1] = src
    end
  end
  for _, dst in ipairs(wezterm.read_dir(CACHE)) do
    local name = dst:match('[^/]+$')
    if not own[name] and not want[name] then os.remove(dst) end
  end
  args[#args + 1] = CACHE .. '/'
  if #args > 3 then wezterm.run_child_process(args) end
  return CACHE
end

return M

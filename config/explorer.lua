-- The explorer's yazi config home. yazi reads its colours only from a theme.toml in
-- YAZI_CONFIG_HOME, and the palette follows the theme chosen in the settings panel, so the
-- theme is generated here from theme.lua's palette into a cache directory beside links
-- to the static config (config/yazi, installed to ~/.config/hivegrid/yazi).
-- Wire: cmd = 'YAZI_CONFIG_HOME=' .. require('explorer').config_home()
local wezterm = require 'wezterm'

local M = {}

local SOURCE = wezterm.home_dir .. '/.config/hivegrid/yazi'
local CACHE = (os.getenv('XDG_CACHE_HOME') or (wezterm.home_dir .. '/.cache')) .. '/hivegrid/yazi'

local function style(t)
  local out = {}
  for _, k in ipairs { 'fg', 'bg' } do
    if t[k] then out[#out + 1] = string.format('%s = "%s"', k, t[k]) end
  end
  for _, k in ipairs { 'bold', 'italic', 'underline', 'reversed', 'crossed' } do
    if t[k] then out[#out + 1] = k .. ' = true' end
  end
  return '{ ' .. table.concat(out, ', ') .. ' }'
end

